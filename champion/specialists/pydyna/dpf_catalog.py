"""PyDPF API catalog (track T1.3a, roadmap PD-09 with PD-04 / PD-05): exact API records of the
installed ansys-dpf-post and ansys-dpf-core.

The same catalog as the PyDyna one (``api_catalog.py``), read from the package files of the
installed ansys-dpf-post (``ansys.dpf.post``) and ansys-dpf-core (``ansys.dpf.core``); nothing
is imported or run, and no DPF server is needed. The two catalogs are peers: a name of one
package that the other re-exports or inherits from is followed.

DPF operators (``ansys/dpf/core/operators/<category>/<name>.py``, generated by Ansys) get
their own records from the operator ``_spec()``: description, input pins (number, name,
types, optional or not, document) and output pins, the internal operator name, and whether
the operator is for LS-DYNA (``(LSDyna)`` in its description: ``"specific"``, or in a pin
document such as the unit system pin: ``"inputs"``). ``find_operators`` filters them by words
(exact text match, no vector search): for example the LS-DYNA binout energies and forces
(``part_internal_energy``, ``interface_resultant_contact_force``, ...).

For the script check (``api_check.check_source``) ``DpfCatalog`` answers like one
``Catalog`` over both packages. The ``inputs`` and ``outputs`` of an operator are checked
against its pins (``op.inputs.data_sources.connect(ds)``, ``op.outputs.fields_container()``);
an operator with repeated pins (``any_input1``, ``any_input2`` ...) takes more at run time, so
its pins are not reported. ``Operator`` itself adds sub-results at run time (``X()``, ``Y()``),
so unknown names on an operator object are not reported.
"""

from __future__ import annotations

import ast
import importlib.metadata
import re
import threading
from dataclasses import dataclass, field
from pathlib import Path

from champion.specialists.pydyna.api_catalog import (DOC_CHARS, Catalog, CatalogError, _class, _clean_doc,
                                                     _summary, _value)

POST_DISTRIBUTION, POST_PACKAGE = "ansys-dpf-post", "ansys.dpf.post"
CORE_DISTRIBUTION, CORE_PACKAGE = "ansys-dpf-core", "ansys.dpf.core"
NAMESPACE = "ansys.dpf"
OPERATORS = f"{CORE_PACKAGE}.operators"
SEARCH_TOOL = "search_pydpf_post"
MAX_OPERATORS = 30
PIN_DOC_CHARS = 400
_WORD_RE = re.compile(r"[a-z0-9]+")


@dataclass
class Operator:
    name: str  # Python class name, for example part_internal_energy
    category: str  # result, math, ... ("" for the top level of operators)
    qualified_name: str
    source_path: str
    line: int
    internal_name: str | None = None  # the DPF name, for example M_IE
    description: str = ""
    inputs: list[dict] = field(default_factory=list)
    outputs: list[dict] = field(default_factory=list)
    inputs_class: str | None = None  # qualified name of InputsX / OutputsX
    outputs_class: str | None = None

    @property
    def lsdyna(self) -> str | None:
        if "lsdyna" in self.description.lower():
            return "specific"
        if any("lsdyna" in (p["document"] or "").lower() for p in self.inputs):
            return "inputs"
        return None

    @property
    def path(self) -> str:
        return f"{self.category}.{self.name}" if self.category else self.name


def _pins(node: ast.AST | None) -> list[dict]:
    pins = []
    if not isinstance(node, ast.Dict):
        return pins
    for key, value in zip(node.keys, node.values):
        if not isinstance(value, ast.Call):
            continue
        args = {k.arg: k.value for k in value.keywords if k.arg}
        types = _value(args.get("type_names"))
        pins.append({"pin": _value(key), "name": _value(args.get("name")),
                     "types": types if isinstance(types, list) else [],
                     "optional": bool(_value(args.get("optional"))),
                     "document": _clean_doc(_value(args.get("document")) or "", PIN_DOC_CHARS)})
    return pins


def _operator(node: ast.ClassDef, module: str, category: str, source_path: str) -> Operator | None:
    """The record of a generated operator class (base Operator with a ``_spec`` static method)."""
    if not any(ast.unparse(b).split(".")[-1] == "Operator" for b in node.bases):
        return None
    op = Operator(node.name, category, f"{module}.{node.name}", source_path, node.lineno)
    for item in ast.walk(node):
        if isinstance(item, ast.FunctionDef) and item.name == "_spec":
            for stmt in ast.walk(item):
                if (isinstance(stmt, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "description"
                                                          for t in stmt.targets)):
                    op.description = _clean_doc(_value(stmt.value) or "", DOC_CHARS)
                if isinstance(stmt, ast.Call) and getattr(stmt.func, "id", None) == "Specification":
                    args = {k.arg: k.value for k in stmt.keywords if k.arg}
                    op.inputs = _pins(args.get("map_input_pin_spec"))
                    op.outputs = _pins(args.get("map_output_pin_spec"))
        if (isinstance(item, ast.Call) and isinstance(item.func, ast.Attribute) and item.func.attr == "__init__"
                and isinstance(item.func.value, ast.Call)):
            args = {k.arg: k.value for k in item.keywords if k.arg}
            name = _value(args.get("name"))
            op.internal_name = name if isinstance(name, str) else None
            for key, attr in (("inputs_type", "inputs_class"), ("outputs_type", "outputs_class")):
                if isinstance(args.get(key), ast.Name):
                    setattr(op, attr, f"{module}.{args[key].id}")
    return op if op.internal_name or op.inputs or op.outputs else None


class _CoreCatalog(Catalog):
    """The ansys-dpf-core catalog; it also collects the operators and the private _Inputs / _Outputs."""

    def __init__(self, root: Path, version: str):
        self.operators: dict[str, Operator] = {}  # qualified name -> operator
        self.base_io: dict[str, dict] = {}  # "_Inputs" / "_Outputs" -> class record
        super().__init__(root, version, CORE_PACKAGE, CORE_DISTRIBUTION, SEARCH_TOOL)

    def _module_parsed(self, module: str, tree: ast.Module, path: Path) -> None:
        if module in (f"{CORE_PACKAGE}.inputs", f"{CORE_PACKAGE}.outputs"):
            for item in tree.body:
                if isinstance(item, ast.ClassDef) and item.name in ("_Inputs", "_Outputs"):
                    self.base_io[item.name] = _class(item, module, self._source_path(path))
        if not module.startswith(OPERATORS + "."):
            return
        rest = module[len(OPERATORS) + 1:].split(".")
        category = ".".join(rest[:-1])
        for item in tree.body:
            if isinstance(item, ast.ClassDef) and not item.name.startswith("_"):
                op = _operator(item, module, category, self._source_path(path))
                if op is not None:
                    self.operators[op.qualified_name] = op


class DpfCatalog:
    """ansys-dpf-post and ansys-dpf-core together: lookups, operator search and the script check."""

    package = NAMESPACE

    def __init__(self, post_root: Path, post_version: str, core_root: Path, core_version: str):
        self.post = Catalog(post_root, post_version, POST_PACKAGE, POST_DISTRIBUTION, SEARCH_TOOL)
        self.core = _CoreCatalog(core_root, core_version)
        self.post.peers = [self.core]
        self.core.peers = [self.post]
        self.distribution = f"{POST_DISTRIBUTION} + {CORE_DISTRIBUTION}"
        self.version = f"{post_version} + {core_version}"
        self._by_name: dict[str, list[Operator]] = {}
        self._io: dict[str, tuple[Operator, str]] = {}  # InputsX / OutputsX -> (operator, "inputs" / "outputs")
        for op in self.core.operators.values():
            self._by_name.setdefault(op.name, []).append(op)
            self._by_name.setdefault(op.path, []).append(op)
            if op.internal_name:
                self._by_name.setdefault(op.internal_name, []).append(op)
            if op.inputs_class:
                self._io[op.inputs_class] = (op, "inputs")
            if op.outputs_class:
                self._io[op.outputs_class] = (op, "outputs")
        for ops in self._by_name.values():  # the category version first, then by name
            ops.sort(key=lambda o: (o.category == "", o.qualified_name))

    # ------------------------------------------------------------ records
    def stats(self) -> dict:
        post, core = self.post.stats(), self.core.stats()
        return {"post_version": self.post.version, "core_version": self.core.version,
                "post_classes": post["api_classes"], "post_functions": post["api_functions"],
                "core_classes": core["api_classes"], "core_functions": core["api_functions"],
                "operators": len(self.core.operators),
                "lsdyna_operators": sum(1 for o in self.core.operators.values() if o.lsdyna == "specific"),
                "skipped_files": post["skipped_files"] + core["skipped_files"]}

    def _catalog(self, path: str) -> Catalog:
        return self.core if path == CORE_PACKAGE or path.startswith(CORE_PACKAGE + ".") else self.post

    def operator_record(self, op: Operator) -> dict:
        required = ", ".join(f"{p['name']}=..." for p in op.inputs if not p["optional"])
        return {"kind": "operator", "name": op.name, "category": op.category, "qualified_name": op.qualified_name,
                "import": f"from ansys.dpf.core import operators as ops  # then ops.{op.path}(...)",
                "internal_name": op.internal_name, "lsdyna": op.lsdyna, "description": op.description,
                "inputs": op.inputs, "outputs": op.outputs,
                "usage": (f"op = ops.{op.path}({required})"
                          + (f"; op.outputs.{op.outputs[0]['name']}()" if op.outputs else "")),
                "package": CORE_DISTRIBUTION, "version": self.core.version, "source_path": op.source_path,
                "line": op.line}

    def _operator_by_name(self, text: str) -> Operator | None:
        for prefix in (f"{OPERATORS}.", "dpf.operators.", "core.operators.", "operators.", "ops."):
            text = text.removeprefix(prefix)
        found = self._by_name.get(text)
        return found[0] if found else None

    def _inherited_member(self, text: str) -> dict | None:
        """Class.member where a base class defines the member (Catalog.lookup sees the class only)."""
        if "." not in text:
            return None
        owner, member = text.rsplit(".", 1)
        qualified = self.post._resolve_class(owner) or self.core._resolve_class(owner)
        found = self.post._defined_in(qualified, member) if qualified else None
        if found is None:
            return None
        record, module = found
        catalog = self._catalog(module)
        defined = next((c for c in catalog._classes.values() if c["module"] == module
                        and c["members"].get(member) is record), None)
        result = {key: value for key, value in record.items() if key != "line"}
        return {**result, "class": qualified, "defined_in": defined["qualified_name"] if defined else module,
                "package": catalog.distribution, "version": catalog.version,
                "source_path": defined["source_path"] if defined else None, "line": record.get("line")}

    def lookup(self, name: str) -> dict:
        """The record of an operator, or of a class, method, property or function of ansys-dpf-post or
        ansys-dpf-core (post first for a short name)."""
        text = str(name or "").strip().removesuffix("()")
        if not text:
            raise CatalogError("name is empty")
        op = self._operator_by_name(text)
        if op is not None:
            return self.operator_record(op)
        if text in self.core.operators:
            return self.operator_record(self.core.operators[text])
        for prefix, catalog in (("post.", self.post), ("dpf.", self.core), ("core.", self.core)):
            if text.startswith(prefix):
                text = f"{catalog.package}.{text[len(prefix):]}"
        if text.startswith(NAMESPACE + "."):  # a re-exported name: ansys.dpf.post.load_simulation
            found = self.resolve(text)
            if found is not None and found["kind"] in ("class", "function", "member"):
                text = found["name"]
        first = self._catalog(text) if text.startswith(NAMESPACE + ".") else self.post
        for catalog in dict.fromkeys((first, self.post, self.core)):
            try:
                return catalog.lookup(text)
            except CatalogError:
                pass
            if text.startswith(NAMESPACE + "."):
                break
        inherited = self._inherited_member(text)
        if inherited is not None:
            return inherited
        close = self.close_names(text.rsplit(".", 1)[-1], [*self.post.names(), *self.core.names(), *self._by_name])
        hint = f" Close names: {', '.join(close)}." if close else f" Use find_dpf_operators or {SEARCH_TOOL}."
        raise CatalogError(f"{text} is not in {self.distribution} {self.version}.{hint}")

    def find_operators(self, query: str, lsdyna: bool = False, category: str | None = None,
                       n_results: int = 10) -> list[dict]:
        """Operators whose name and description have the words of ``query`` (best first)."""
        words = [w for w in _WORD_RE.findall(str(query).lower()) if len(w) > 1]
        if not words and not lsdyna:
            raise CatalogError("query is empty")
        categories = sorted({o.category for o in self.core.operators.values()})
        if category and category not in categories:
            raise CatalogError(f"unknown category {category}; known: {', '.join(c for c in categories if c)}")
        scored = []
        for op in self.core.operators.values():
            if (lsdyna and not op.lsdyna) or (category and op.category != category):
                continue
            name_words = set(op.name.lower().split("_"))
            text_words = set(_WORD_RE.findall(f"{op.description} {' '.join(p['name'] or '' for p in op.inputs)}".lower()))
            score = sum(3 if w in name_words else 1 if w in text_words or w in op.name.lower() else 0
                        for w in words)
            if words and not score:
                continue
            if lsdyna and op.lsdyna == "specific":
                score += 0.5
            # same score: the name with fewer other words first (part_internal_energy before part_eroded_...)
            scored.append((-score, len(name_words), op.qualified_name, op))
        scored.sort(key=lambda item: item[:3])
        return [{"operator": f"ops.{op.path}", "internal_name": op.internal_name, "lsdyna": op.lsdyna,
                 "score": -s, "summary": _summary(op.description)} for s, _, _, op in scored[:n_results]]

    # ------------------------------------------------------------ for the script check (api_check.py)
    def related(self, name: str) -> bool:
        return self.post.related(name) or self.core.related(name)

    def label(self, path: str | None = None) -> str:
        if path and (path == NAMESPACE or not path.startswith(NAMESPACE + ".")):
            return f"{self.distribution} {self.version}"
        return self._catalog(path or "").label(path)

    def resolve(self, path: str, as_module: bool = False) -> dict | None:
        if path == NAMESPACE or NAMESPACE.startswith(path + "."):
            return {"kind": "module", "name": path}
        if not path.startswith(NAMESPACE + "."):
            return None
        if path.split(".")[2] not in ("post", "core"):
            return {"kind": "variable", "name": path}  # another ansys.dpf distribution (gate, ...): not checked
        return self._catalog(path).resolve(path, as_module=as_module)

    def module_members(self, module: str) -> list[str]:
        if module == NAMESPACE:
            return ["core", "post"]
        return self._catalog(module).module_members(module)

    def _pins(self, qualified: str) -> list[dict]:
        op, side = self._io[qualified]
        return op.inputs if side == "inputs" else op.outputs

    def class_members(self, qualified: str) -> tuple[dict, bool]:
        if qualified in self._io:
            side = self._io[qualified][1]
            members, _ = self.core.class_members(qualified)
            base = self.core.base_io.get("_Inputs" if side == "inputs" else "_Outputs")
            for name, record in (base or {}).get("members", {}).items():
                members.setdefault(name, record)
            pins = self._pins(qualified)
            for pin in pins:
                if pin["name"]:
                    members.setdefault(pin["name"], {"kind": "property", "name": pin["name"],
                                                     "type": "Input" if side == "inputs" else "Output",
                                                     "settable": False, "doc": pin["document"]})
            # repeated pins (any_input, any_input ...: any_input1, any_input2 ...): more of them at run time
            names = [p["name"] or "" for p in pins]
            numbered = len(names) != len(set(names)) or any(re.search(r"\d$", n) for n in names)
            return members, qualified not in self.core._dynamic and not numbered
        return self.core.class_members(qualified)

    def member_type(self, qualified: str, member: str, call: bool = False) -> str | None:
        if qualified in self._io and not call:
            side = self._io[qualified][1]
            if member in {p["name"] for p in self._pins(qualified)}:
                found = f"{CORE_PACKAGE}.{side}.{'Input' if side == 'inputs' else 'Output'}"
                return found if found in self.core._classes else None
        return self.core.member_type(qualified, member, call)

    def function_type(self, qualified: str) -> str | None:
        return self.core.function_type(qualified)

    def keyword_api(self, class_name: str) -> dict:  # never reached: DPF has no keyword classes
        raise CatalogError(f"{class_name} is not a keyword class")

    def close_names(self, text: str, names: list[str]) -> list[str]:
        return self.core.close_names(text, names)


def installed_dpf() -> tuple[Path, str, Path, str]:
    """(post folder, post version, core folder, core version) of the installed packages."""
    found: list = []
    for distribution, package in ((POST_DISTRIBUTION, POST_PACKAGE), (CORE_DISTRIBUTION, CORE_PACKAGE)):
        try:
            dist = importlib.metadata.distribution(distribution)
        except importlib.metadata.PackageNotFoundError:
            raise CatalogError(f"{distribution} is not installed in the Python that runs Champion "
                               f"(pip install {distribution})") from None
        root = Path(dist.locate_file(package.replace(".", "/")))
        if not (root / "__init__.py").is_file():
            raise CatalogError(f"{distribution} {dist.version} is installed but {root} has no package files")
        found += [root, dist.version]
    return tuple(found)


_CATALOGS: dict[tuple, DpfCatalog] = {}
_CATALOGS_LOCK = threading.Lock()


def dpf_catalog_for(post_root: Path | None = None, post_version: str | None = None,
                    core_root: Path | None = None, core_version: str | None = None) -> DpfCatalog:
    """The DPF catalog (default: the installed packages), built once per folders and versions."""
    if post_root is None:
        post_root, post_version, core_root, core_version = installed_dpf()
    key = (Path(post_root).resolve(), str(post_version), Path(core_root).resolve(), str(core_version))
    with _CATALOGS_LOCK:
        if key not in _CATALOGS:
            _CATALOGS[key] = DpfCatalog(*key)
        return _CATALOGS[key]
